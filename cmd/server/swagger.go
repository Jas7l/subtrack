package main

import (
	"net/http"

	"github.com/gorilla/mux"
	httpSwagger "github.com/swaggo/http-swagger"

	_ "subtrack/docs" // generated by `make swagger`; registers the OpenAPI spec
)

// mountSwagger puts the Swagger UI on /swagger/ and the raw spec on
// /swagger/doc.json; /swagger redirects to the UI.
//
// The spec URL stays relative ("doc.json"), never absolute: behind a proxy
// that serves the app under a path prefix, an absolute URL would resolve
// against the origin and drop the prefix.
func mountSwagger(r *mux.Router) {
	r.Handle("/swagger", http.RedirectHandler("/swagger/index.html", http.StatusMovedPermanently)).Methods("GET")
	r.PathPrefix("/swagger/").Handler(httpSwagger.Handler(httpSwagger.URL("doc.json"))).Methods("GET")
}
